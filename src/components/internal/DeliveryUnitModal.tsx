import React, { useState, useEffect } from 'react';
import { Modal } from '../common/Modal';
import { DeliveryUnit } from '../../types/dairy';
import { Truck, Hash, User, Phone, Clock, AlertCircle } from 'lucide-react';

interface DeliveryUnitModalProps {
  isOpen: boolean;
  onClose: () => void;
  onSave: (data: {
    name: string;
    vehicleNumber: string;
    driverName: string;
    driverPhone?: string;
    outTime?: string;
    isActive?: boolean;
  }) => Promise<void>;
  unitToEdit?: DeliveryUnit | null;
}

export const DeliveryUnitModal: React.FC<DeliveryUnitModalProps> = ({
  isOpen,
  onClose,
  onSave,
  unitToEdit,
}) => {
  const isEditing = Boolean(unitToEdit);

  const [name, setName] = useState('');
  const [vehicleNumber, setVehicleNumber] = useState('');
  const [driverName, setDriverName] = useState('');
  const [driverPhone, setDriverPhone] = useState('');
  const [outTime, setOutTime] = useState('');
  const [isActive, setIsActive] = useState(true);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [formError, setFormError] = useState<string | null>(null);

  useEffect(() => {
    if (unitToEdit) {
      setName(unitToEdit.name);
      setVehicleNumber(unitToEdit.vehicleNumber);
      setDriverName(unitToEdit.driverName);
      setDriverPhone(unitToEdit.driverPhone || '');
      setOutTime(unitToEdit.outTime || '');
      setIsActive(unitToEdit.isActive);
    } else {
      setName('');
      setVehicleNumber('');
      setDriverName('');
      setDriverPhone('');
      setOutTime('');
      setIsActive(true);
    }
    setFormError(null);
  }, [unitToEdit, isOpen]);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setFormError(null);

    // Validation
    if (!name.trim()) {
      setFormError('Delivery unit name is required (e.g. Route A Van, Pune East Tanker).');
      return;
    }
    if (!vehicleNumber.trim()) {
      setFormError('Vehicle number is required (e.g. MH 12 AB 1234).');
      return;
    }
    if (!driverName.trim()) {
      setFormError('Driver name is required.');
      return;
    }

    if (driverPhone.trim() && !/^\+?[0-9\s-]{10,15}$/.test(driverPhone.trim())) {
      setFormError('Please enter a valid 10-digit mobile number.');
      return;
    }

    setIsSubmitting(true);
    try {
      await onSave({
        name: name.trim(),
        vehicleNumber: vehicleNumber.trim().toUpperCase(),
        driverName: driverName.trim(),
        driverPhone: driverPhone.trim() || undefined,
        outTime: outTime.trim() || undefined,
        isActive,
      });
      onClose();
    } catch (err: any) {
      setFormError(err.message || 'Failed to save delivery unit.');
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title={isEditing ? `Edit Delivery Unit: ${unitToEdit?.name}` : 'Register New Delivery Unit'}
      subtitle={
        isEditing
          ? `Chalan #${unitToEdit?.chalanNumber} (Read-only database sequence)`
          : 'Assign delivery vehicle, dedicated driver, and unique chalan sequence'
      }
      maxWidth="md"
    >
      <form onSubmit={handleSubmit} className="space-y-4 text-xs font-sans">
        {formError && (
          <div className="p-3 bg-rose-50 border border-rose-200 text-rose-700 rounded-xl flex items-start gap-2 animate-in fade-in">
            <AlertCircle className="w-4 h-4 text-rose-600 shrink-0 mt-0.5" />
            <span className="text-xs">{formError}</span>
          </div>
        )}

        {/* Chalan Number (Read-only, auto-generated) */}
        <div>
          <label className="block text-[11px] font-bold text-slate-700 uppercase tracking-wider mb-1">
            Chalan Number
          </label>
          <div className="relative">
            <Hash className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2 pointer-events-none" />
            <input
              type="text"
              readOnly
              disabled
              value={unitToEdit ? unitToEdit.chalanNumber : 'Auto-generated by system (e.g. CHLN-2026-0001)'}
              className="w-full pl-9 pr-3 py-2 bg-slate-100 border border-slate-200 rounded-lg text-xs text-slate-500 font-mono-numbers cursor-not-allowed select-none"
            />
          </div>
          <p className="text-[10px] text-slate-400 mt-1">
            Chalan numbers are unique, concurrency-safe sequential identifiers managed by PostgreSQL.
          </p>
        </div>

        {/* Unit Name */}
        <div>
          <label className="block text-[11px] font-bold text-slate-700 uppercase tracking-wider mb-1">
            Unit Name <span className="text-rose-500">*</span>
          </label>
          <div className="relative">
            <Truck className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2 pointer-events-none" />
            <input
              type="text"
              required
              value={name}
              onChange={(e) => setName(e.target.value)}
              placeholder="e.g. Route 1 — Kothrud Morning Delivery Van"
              className="w-full pl-9 pr-3 py-2 bg-slate-50 border border-slate-200 rounded-lg text-xs focus:ring-2 focus:ring-blue-100 focus:border-blue-600 focus:bg-white focus:outline-none transition-colors"
            />
          </div>
        </div>

        {/* Vehicle Number & Driver Name */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          <div>
            <label className="block text-[11px] font-bold text-slate-700 uppercase tracking-wider mb-1">
              Vehicle Number <span className="text-rose-500">*</span>
            </label>
            <input
              type="text"
              required
              value={vehicleNumber}
              onChange={(e) => setVehicleNumber(e.target.value.toUpperCase())}
              placeholder="e.g. MH 12 AB 1234"
              className="w-full px-3 py-2 bg-slate-50 border border-slate-200 rounded-lg text-xs font-mono uppercase focus:ring-2 focus:ring-blue-100 focus:border-blue-600 focus:bg-white focus:outline-none transition-colors"
            />
          </div>

          <div>
            <label className="block text-[11px] font-bold text-slate-700 uppercase tracking-wider mb-1">
              Driver Name <span className="text-rose-500">*</span>
            </label>
            <div className="relative">
              <User className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2 pointer-events-none" />
              <input
                type="text"
                required
                value={driverName}
                onChange={(e) => setDriverName(e.target.value)}
                placeholder="e.g. Ramesh Patil"
                className="w-full pl-9 pr-3 py-2 bg-slate-50 border border-slate-200 rounded-lg text-xs focus:ring-2 focus:ring-blue-100 focus:border-blue-600 focus:bg-white focus:outline-none transition-colors"
              />
            </div>
          </div>
        </div>

        {/* Driver Phone & Out Time */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          <div>
            <label className="block text-[11px] font-bold text-slate-700 uppercase tracking-wider mb-1">
              Driver Phone
            </label>
            <div className="relative">
              <Phone className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2 pointer-events-none" />
              <input
                type="tel"
                value={driverPhone}
                onChange={(e) => setDriverPhone(e.target.value)}
                placeholder="e.g. 9876543210"
                className="w-full pl-9 pr-3 py-2 bg-slate-50 border border-slate-200 rounded-lg text-xs font-mono-numbers focus:ring-2 focus:ring-blue-100 focus:border-blue-600 focus:bg-white focus:outline-none transition-colors"
              />
            </div>
          </div>

          <div>
            <label className="block text-[11px] font-bold text-slate-700 uppercase tracking-wider mb-1">
              Out Time (Departure)
            </label>
            <div className="relative">
              <Clock className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2 pointer-events-none" />
              <input
                type="text"
                value={outTime}
                onChange={(e) => setOutTime(e.target.value)}
                placeholder="e.g. 05:30 AM or 14:00"
                className="w-full pl-9 pr-3 py-2 bg-slate-50 border border-slate-200 rounded-lg text-xs focus:ring-2 focus:ring-blue-100 focus:border-blue-600 focus:bg-white focus:outline-none transition-colors"
              />
            </div>
          </div>
        </div>

        {/* Active Toggle */}
        <div className="pt-2 flex items-center justify-between border-t border-slate-100">
          <div>
            <span className="text-xs font-semibold text-slate-800 block">Unit Active Status</span>
            <span className="text-[11px] text-slate-500">
              Active units are selectable for trip assignment and driver sheet generation.
            </span>
          </div>
          <label className="relative inline-flex items-center cursor-pointer">
            <input
              type="checkbox"
              checked={isActive}
              onChange={(e) => setIsActive(e.target.checked)}
              className="sr-only peer"
            />
            <div className="w-10 h-5 bg-slate-200 peer-focus:outline-none rounded-full peer peer-checked:after:translate-x-full peer-checked:after:border-white after:content-[''] after:absolute after:top-[2px] after:left-[2px] after:bg-white after:border-slate-300 after:border after:rounded-full after:h-4 after:w-4 after:transition-all peer-checked:bg-blue-600"></div>
          </label>
        </div>

        {/* Actions */}
        <div className="pt-4 flex items-center justify-end gap-2 border-t border-slate-100">
          <button
            type="button"
            onClick={onClose}
            disabled={isSubmitting}
            className="px-4 py-2 border border-slate-200 text-slate-600 hover:bg-slate-100 rounded-xl text-xs font-semibold transition-colors"
          >
            Cancel
          </button>
          <button
            type="submit"
            disabled={isSubmitting}
            className="px-5 py-2 bg-blue-600 hover:bg-blue-700 disabled:opacity-50 text-white rounded-xl text-xs font-bold shadow-sm transition-all flex items-center gap-1.5"
          >
            {isSubmitting ? (
              <span>Saving...</span>
            ) : isEditing ? (
              <span>Update Delivery Unit</span>
            ) : (
              <span>Create Delivery Unit</span>
            )}
          </button>
        </div>
      </form>
    </Modal>
  );
};
